export function getHelpCategoryById(categoryId: string | undefined) {
  return helpCategories.find((category) => category.id === categoryId);
}

export function isHelpCategoryId(value: string | undefined): value is HelpCategoryId {
  return Boolean(value && helpCategoryIds.includes(value as HelpCategoryId));
}

export function getHelpArticleBySlug(slug: string | undefined) {
  return helpArticles.find((article) => article.slug === slug);
}

export function getHelpArticlesByCategory(categoryId: string | undefined) {
  if (!isHelpCategoryId(categoryId)) {
    return [];
  }

  return helpArticles.filter((article) => article.categoryId === categoryId);
}

export function getPopularHelpArticles() {
  return helpArticles.filter((article) => article.popular);
}

export function getQuickStartArticles() {
  return helpArticles.filter((article) => article.quickStart);
}

export function getRelatedHelpArticles(article: HelpArticle) {
  return (article.relatedArticles ?? [])
    .map((slug) => getHelpArticleBySlug(slug))
    .filter((related): related is HelpArticle => Boolean(related));
}

export function getHelpArticleCountByCategory(categoryId: HelpCategoryId) {
  return helpArticles.filter((article) => article.categoryId === categoryId).length;
}

export function searchHelpArticles(
  query: string,
  options: { categoryId?: string; limit?: number } = {},
) {
  const normalizedQuery = normalizeHelpText(query);
  const categoryId = isHelpCategoryId(options.categoryId) ? options.categoryId : undefined;
  const source = categoryId
    ? helpArticles.filter((article) => article.categoryId === categoryId)
    : helpArticles;

  if (!normalizedQuery) {
    return source.slice(0, options.limit ?? source.length);
  }

  const scored = source
    .map((article) => {
      const category = getHelpCategoryById(article.categoryId);
      const haystack = normalizeHelpText(
        [
          article.title,
          article.summary,
          category?.title,
          category?.description,
          ...article.keywords,
          ...article.whenToUse,
          ...article.steps,
          ...(article.notes ?? []),
          ...(article.commonIssues ?? []).flatMap((issue) => [issue.title, issue.solution]),
        ].join(" "),
      );

      if (!haystack.includes(normalizedQuery)) {
        return null;
      }

      let score = 1;
      if (normalizeHelpText(article.title).includes(normalizedQuery)) score += 5;
      if (article.keywords.some((keyword) => normalizeHelpText(keyword).includes(normalizedQuery))) score += 3;
      if (normalizeHelpText(article.summary).includes(normalizedQuery)) score += 2;

      return { article, score };
    })
    .filter((item): item is { article: HelpArticle; score: number } => Boolean(item))
    .sort((a, b) => b.score - a.score || a.article.readMinutes - b.article.readMinutes);

  return scored.slice(0, options.limit ?? scored.length).map((item) => item.article);
}

function normalizeHelpText(value: string) {
  return value
    .trim()
    .toLowerCase()
    .replace(/ي/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/[‌\s]+/g, " ");
}
